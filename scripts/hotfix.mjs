/**
 * Hot-fix deployment: ship src/index.js into the RUNNING dsh web without a
 * restart.
 *
 * The loader's ESM cache never invalidates by mtime, so the only way to load
 * fixed host code into a running profile is a module URL that has never been
 * imported. This script stamps a fresh copy (`src/boot-<epoch>.js`), points
 * the package exports at it, and prints the remove+add commands that make
 * the running host apply the row anew (the plugin add/remove writes are
 * hot-applied by the host's plugin management).
 *
 * The newest `boot-*.js` always holds the deployed code; `npm run build`
 * keeps `lib/client.js` (the browser half) in sync — the browser picks it up
 * on the next page refresh.
 */
import { copyFileSync, readdirSync, unlinkSync, writeFileSync, readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const stamp = Date.now()
const entryName = `boot-${String(stamp)}.js`

copyFileSync(join(root, 'src/index.js'), join(root, 'src', entryName))
writeFileSync(
  join(root, 'src', entryName),
  [
    `// GENERATED by scripts/hotfix.mjs at ${new Date().toISOString()} — physical copy of src/index.js.`,
    '// Fresh URL per deploy: the running host has never imported this module, so',
    '// its ESM cache cannot serve a stale copy. Edit src/index.js, rerun hotfix.',
    '',
  ].join('\n') + readFileSync(join(root, 'src/index.js'), 'utf8'),
)

// Point the package at the fresh entry.
const manifestPath = join(root, 'package.json')
const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'))
manifest.main = `./src/${entryName}`
manifest.exports['.'] = `./src/${entryName}`
writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`)

// Prune older stamped entries (keep the newest only).
for (const file of readdirSync(join(root, 'src'))) {
  if (/^boot-\d+\.js$/.test(file) && file !== entryName) {
    try {
      unlinkSync(join(root, 'src', file))
    } catch {}
  }
}

console.log(`[tunnel-gate] hotfix entry: src/${entryName}`)
console.log('[tunnel-gate] now apply it to the running profile:')
console.log(`  dsh plugin --profile web remove dsh-tunnel-gate && dsh plugin --profile web add link:${root}`)
